def _cells(line: str) -> list[str]:
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    out, cur, esc = [], "", False
    for ch in line:
        if ch == "\\" and not esc:
            esc = True
            cur += ch
            continue
        if ch == "|" and not esc:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
        esc = False
    out.append(cur.strip())
    return out


def read_ledger(path: str) -> list[dict]:
    """All rows of every Markdown table whose header has a 'verdict' column."""
    rows: list[dict] = []
    lines = open(path, encoding="utf-8").read().splitlines()
    i = 0
    while i < len(lines):
        if lines[i].lstrip().startswith("|") and i + 1 < len(lines) and re.match(r"^\s*\|?\s*:?-{3,}", lines[i + 1]):
            head = [h.lower() for h in _cells(lines[i])]
            i += 2
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                if "verdict" in head:
                    vals = _cells(lines[i]) + [""] * len(head)
                    row = dict(zip(head, vals[:len(head)]))
                    row["_line"] = i + 1
                    rows.append(row)
                i += 1
            continue
        i += 1
    return rows


def norm_verdict(v: str, profile: dict) -> tuple[str, str]:
    """('GAP', '') or ('CONDITIONAL', 'Conj. 1') or ('?', original)."""
    raw = re.sub(r"[*_`]", "", v or "").strip()
    m = re.match(r"(?i)^(conditional)\s*(?:\((.*)\)|on\s+(.*))?$", raw)
    if m and "CONDITIONAL" in profile["verdicts"]:
        return "CONDITIONAL", (m.group(2) or m.group(3) or "").strip()
    up = re.sub(r"\s+", " ", raw.upper().replace("_", " "))
    up = {"PARTIAL": "PARTIALLY CONFIRMED", "PARTIALLY": "PARTIALLY CONFIRMED", "UNCHECKED": "NOT CHECKED",
          "VALID": "VERIFIED", "VALID WITH FIX": "VERIFIED WITH FIXES", "VERIFIED WITH FIX": "VERIFIED WITH FIXES",
          "STATS INCONSISTENT": "STATS-INCONSISTENT", "CONVENTION ISSUE": "CONVENTION-ISSUE",
          "SUPERSEDED PARAMETER": "SUPERSEDED-PARAMETER"}.get(up, up)
    return (up, "") if up in profile["verdicts"] else ("?", raw)


def _yes(v: str) -> bool:
    return bool(re.match(r"(?i)^\s*(yes|y|true|confirmed|verified|是|已核实|✓)\b", v or ""))


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def analyse(rows: list[dict], profile_name: str) -> dict:
    prof = PROFILES[profile_name]
    out = {"rows": [], "unknown": [], "open": [], "severe": [], "other": [], "ok": [], "nc": [], "counts": {}}
    for r in rows:
        v, extra = norm_verdict(r.get("verdict", ""), prof)
        r = dict(r, _verdict=v, _extra=extra)
        out["rows"].append(r)
        if v == "?":
            out["unknown"].append(r)
            continue
        out["counts"][v] = out["counts"].get(v, 0) + 1
        if v in prof["severe"]:
            (out["severe"] if _yes(r.get("verified", "")) else out["open"]).append(r)
        elif v == "NOT CHECKED":
            out["nc"].append(r)
        elif v in prof["ok"]:
            out["ok"].append(r)
        else:
            out["other"].append(r)
    final = bool(out["rows"]) and not out["open"] and not out["unknown"]
    worst = max((prof["verdicts"][r["_verdict"]] for r in out["rows"] if r["_verdict"] != "?"), default=-1)
    worst_names = sorted({r["_verdict"] for r in out["rows"]
                          if r["_verdict"] != "?" and prof["verdicts"][r["_verdict"]] == worst})
    out.update(final=final, worst=" / ".join(worst_names) or "-",
               exit=2 if not final else (1 if out["severe"] else 0))
    return out


def conclusion(a: dict, profile_name: str, lang: str) -> str:
    prof = PROFILES[profile_name]
    n = len(a["rows"])
    order = sorted(prof["verdicts"], key=lambda k: -prof["verdicts"][k])
    parts = [f"{k} {a['counts'][k]}" for k in order if a["counts"].get(k)]
    sev = ", ".join(f"{r.get('item') or r.get('id')}" for r in a["severe"])
    if lang == "zh":
        s = f"共 {n} 条：" + "，".join(parts) + "。"
        if not a["final"]:
            s += f"报告未定稿：{len(a['open'])} 条严重问题未经主会话核实，{len(a['unknown'])} 条判定不在词表中。"
        elif a["severe"]:
            s += f"已确认的严重问题：{sev}。"
        else:
            s += "没有已确认的严重问题。"
        if a["nc"]:
            s += f"{len(a['nc'])} 条未检查，结论不覆盖这些条目。"
        return s
    s = f"{n} items: " + ", ".join(parts) + "."
    if not a["final"]:
        s += (f" NOT FINAL: {len(a['open'])} severe findings not verified by the main session, "
              f"{len(a['unknown'])} verdicts outside the vocabulary.")
    elif a["severe"]:
        s += f" Confirmed severe findings: {sev}."
    else:
        s += " No confirmed severe finding."
    if a["nc"]:
        s += f" {len(a['nc'])} items were not checked; the conclusion does not cover them."
    return s


def _table(rows: list[dict], cols: list[str]) -> list[str]:
    if not rows:
        return []
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        vals = []
        for c in cols:
            v = r.get(c, "")
            if c == "verdict" and r.get("_extra"):
                v = f"{r['_verdict']} ({r['_extra']})"
            vals.append(str(v).replace("\n", " "))
        out.append("| " + " | ".join(vals) + " |")
    return out


def render(ledger: str, profile_name: str, lang: str = "en", manuscripts: list[str] | None = None,
           version: str = "", extra_header: list[str] | None = None) -> tuple[str, dict]:
    prof = PROFILES[profile_name]
    T = TEXT[lang]
    rows = read_ledger(ledger)
    a = analyse(rows, profile_name)
    cols = []
    for r in rows:
        for k in r:
            if not k.startswith("_") and k not in cols:
                cols.append(k)
    out = [f"# {prof['title'][lang]}", ""]
    if "disclaimer" in prof:
        out += [f"> {prof['disclaimer'][lang]}", ""]
    out += [f"- {T['date']}: {dt.date.today().isoformat()}", f"- {T['version']}: {version or '-'}",
            f"- {T['overall']}: **{a['worst']}** ({T['final'] if a['final'] else T['notfinal']})"]
    if manuscripts:
        out.append(f"- {T['files']}: " + "; ".join(f"`{os.path.basename(m)}` {sha256(m)[:16]}…" for m in manuscripts))
    out += extra_header or []
    out += ["", f"## {T['conclusion']}", "", conclusion(a, profile_name, lang), ""]
    for key, title in (("unknown", T["unknown"]), ("open", T["open"]), ("severe", T["severe"]),
                       ("other", T["other"]), ("nc", T["nc"]), ("ok", T["ok"])):
        if a[key]:
            out += [f"## {title} ({len(a[key])})", ""] + _table(a[key], cols) + [""]
    out += ["---", "", f"*{T['generated']}*", ""]
    return "\n".join(out), a


def main_cli(profile_name: str, argv=None, prog: str = "report") -> int:
    import argparse
    ap = argparse.ArgumentParser(prog=prog, description=f"Compute the {profile_name} report from a findings ledger. "
                                 "Exit 0: no confirmed severe finding; 1: confirmed severe findings; 2: not final.")
    ap.add_argument("ledger", help="Markdown file with a table containing at least the columns verdict and verified")
    ap.add_argument("--out", required=True)
    ap.add_argument("--lang", choices=["en", "zh"], default="en")
    ap.add_argument("--manuscript", nargs="*", default=[], help="files whose SHA-256 is recorded in the report")
    ap.add_argument("--version", default="", help="e.g. a git commit or the PIN.json hash")
    args = ap.parse_args(argv)
    text, a = render(args.ledger, profile_name, args.lang, args.manuscript, args.version)
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    status = "final" if a["final"] else "NOT FINAL"
    print(f"{len(a['rows'])} items; overall {a['worst']}; {status}; confirmed severe {len(a['severe'])}, "
          f"unverified severe {len(a['open'])}, unknown verdicts {len(a['unknown'])} -> {args.out}")
    return a["exit"]
