"""findings.py - findings ledgers and the reports computed from them.

An audit ends in a findings table. The report, including its conclusion, is computed from that
table, so the conclusion cannot say more than the table supports:
- every verdict must belong to the skill's vocabulary;
- a severe verdict (INVALID, GAP, confirmed error, mismatch, ...) counts only when the main session
  has verified it (column "verified" = yes); otherwise the report is not final;
- the conclusion sentence, the counts, and the overall verdict are derived, not written.

Ledger format (Markdown; extra columns are kept and shown):

| id | item | location | verdict | evidence | verified |
|---|---|---|---|---|---|
| R1 | thm:main | main.tex:182 | VERIFIED WITH FIXES | steps/G1.md; Fano conditioned on support | yes |

Exit codes of report(): 0 = no confirmed severe finding; 1 = at least one confirmed severe finding;
2 = the report is not final (unverified severe findings, unknown verdicts or an empty ledger).
"""
